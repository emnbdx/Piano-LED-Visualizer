const SIMPLE_LANGUAGES = {en: "English", fr: "Français"};

function simpleLanguage() {
    const match = document.cookie.match(/(?:^|; )lang=([^;]*)/);
    const wanted = match ? decodeURIComponent(match[1]) : (navigator.language || "en").slice(0, 2);
    return SIMPLE_TEXTS[wanted] ? wanted : "en";
}

function setSimpleLanguage(lang) {
    const expires = new Date(Date.now() + 365 * 24 * 3600 * 1000).toUTCString();
    document.cookie = `lang=${encodeURIComponent(lang)};expires=${expires};path=/`;
}

function t(key, vars) {
    let text = SIMPLE_TEXTS[simpleLanguage()][key] || SIMPLE_TEXTS.en[key] || key;
    if (vars) {
        for (const name in vars) {
            text = text.replace(`{${name}}`, vars[name]);
        }
    }
    return text;
}

// Fill every element carrying data-i18n / data-i18n-placeholder / data-i18n-title
function translatePage(root) {
    const scope = root || document;
    document.documentElement.lang = simpleLanguage();
    scope.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = t(el.dataset.i18n); });
    scope.querySelectorAll("[data-i18n-placeholder]").forEach(el => { el.placeholder = t(el.dataset.i18nPlaceholder); });
    scope.querySelectorAll("[data-i18n-title]").forEach(el => { el.title = t(el.dataset.i18nTitle); });
    scope.querySelectorAll("[data-i18n-label]").forEach(el => { el.setAttribute("aria-label", t(el.dataset.i18nLabel)); });
}
